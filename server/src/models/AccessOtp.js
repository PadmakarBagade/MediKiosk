const mongoose = require('mongoose');

const accessOtpSchema = new mongoose.Schema(
  {
    doctorId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    patientId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    otpCode: {
      type: String,
      required: true,
    },
    expiresAt: {
      type: Date,
      required: true,
    },
    verified: {
      type: Boolean,
      default: false,
    },
  },
  { timestamps: true }
);

accessOtpSchema.index({ doctorId: 1, patientId: 1, createdAt: -1 });

module.exports = mongoose.model('AccessOtp', accessOtpSchema);
